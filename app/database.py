"""Async SQLAlchemy engine, session factory and declarative base."""

from sqlalchemy import MetaData
from sqlalchemy.ext.asyncio import async_sessionmaker, create_async_engine
from sqlalchemy.orm import DeclarativeBase

from app.config import settings

engine = create_async_engine(
    settings.db_uri,
    pool_size=settings.db_pool_size,
    max_overflow=settings.db_max_overflow,
    pool_recycle=settings.db_pool_recycle_seconds,
    pool_timeout=settings.db_pool_timeout_seconds,
    pool_pre_ping=True,
    echo=settings.db_echo,
    # Keep bound values out of exception messages and echo output: a failed
    # INSERT into ``user`` would otherwise log its ``password_hash``.
    hide_parameters=True,
)

# ``expire_on_commit=False``: rows read before a commit keep their values,
# so an endpoint can serialize what it just saved without another round trip.
SessionFactory = async_sessionmaker(bind=engine, autoflush=False, expire_on_commit=False)


class Base(DeclarativeBase):
    # Deterministic constraint names, so autogenerated migrations can drop
    # and alter constraints by name instead of guessing what Postgres chose.
    metadata = MetaData(
        naming_convention={
            "ix": "ix_%(column_0_label)s",
            "uq": "uq_%(table_name)s_%(column_0_name)s",
            "ck": "ck_%(table_name)s_%(constraint_name)s",
            "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
            "pk": "pk_%(table_name)s",
        }
    )
